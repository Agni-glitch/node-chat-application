const mongoose = require("mongoose");
const config = require("../config/env");

const messageSchema = new mongoose.Schema(
  {
    chatId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "chats",
      required: true,
    },
    sender: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "users",
      required: true,
    },
    text: {
      type: String,
      trim: true,
      maxlength: [5000, "Message is too long (max 5000 characters)"],
      default: "",
    },
    read: {
      type: Boolean,
      default: false,
    },
    // Groups only: members (other than the sender) who have seen the message. When every
    // other member has seen it, `read` becomes true and `readAt` starts the disappearing timer.
    readBy: {
      type: [{ type: mongoose.Schema.Types.ObjectId, ref: "users" }],
      default: undefined,
    },
    // When the recipient saw the message. Seen messages are deleted SEEN_MESSAGE_TTL_SECONDS later.
    readAt: {
      type: Date,
    },
    image: {
      type: String,
      required: false,
    },
    // Set when the message was generated by an AI model. `sender` is then the user who
    // asked (the model's owner). Stored as a snapshot so it still renders if the model is deleted.
    bot: {
      type: new mongoose.Schema(
        {
          id: { type: mongoose.Schema.Types.ObjectId, ref: "bots" },
          name: String,
          model: String,
          kind: String,
          provider: String,
        },
        { _id: false }
      ),
      default: undefined,
    },
    // Cloudinary id, so the image is deleted together with the message.
    imagePublicId: {
      type: String,
      select: false,
    },
  },
  {
    timestamps: true,
    toJSON: {
      transform(doc, ret) {
        delete ret.imagePublicId;
        delete ret.__v;
        return ret;
      },
    },
  }
);

messageSchema.index({ chatId: 1, createdAt: 1 });
messageSchema.index({ read: 1, readAt: 1 });
// Safety net only: the sweeper (services/messageCleanup.js) normally deletes seen messages
// first and notifies clients. MongoDB's TTL monitor runs about once a minute.
messageSchema.index({ readAt: 1 }, { expireAfterSeconds: config.seenMessageTtlSeconds + 60, name: "readAt_ttl" });

module.exports = mongoose.model("messages", messageSchema);
